function isQuestionValid(qText) {
    if (!qText) return false;
    let plainText = qText.replace(/<[^>]*>?/gm, '');
    if (/માસ્ટર\s*(ચાવી|ટિપ્સ|ટ્રીક|કી)/i.test(plainText)) { return false; }
    return true;
}

function cleanQuestionText(qText) {
    if (!qText) return qText;
    let cleaned = qText.replace(/^(ઉદાહરણ\s*[\d\.]+\s*[:\-]|સ્વાધ્યાય\s*[\d\.]+\s*[\-\:]\s*પ્રશ્ન\s*[\d\w\(\)]*\s*[:\-])\s*/i, '');
    cleaned = cleaned.replace(/^<b>(ઉદાહરણ\s*[\d\.]+\s*[:\-]|સ્વાધ્યાય\s*[\d\.]+\s*[\-\:]\s*પ્રશ્ન\s*[\d\w\(\)]*\s*[:\-])<\/b>\s*/i, '');
    return cleaned;
}

