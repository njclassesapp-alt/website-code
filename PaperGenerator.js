function generateSmartRevision(multiplier) {
    // જૂના રિવિઝન પ્રશ્નો કાઢી નાખવા અને મેઈન પ્રશ્નો તારવવા
    let originalQs = {};
    for(let key in selectedQuestions) {
        if(!key.startsWith("rev_")) {
            originalQs[key] = selectedQuestions[key];
        } else {
            delete selectedQuestions[key];
        }
    }

    let neededMult = parseInt(multiplier) || 2;
    let addedTotal = 0;

    // દરેક પસંદ કરેલા પ્રશ્ન માટે લોજીક ચલાવો
    for(let key in originalQs) {
        let q = originalQs[key];
        let targetChap = q.chap;
        let targetTab = q.tab;
        let targetMarks = q.marks; // જો યુઝરે માર્ક્સ બદલ્યા હશે તો તે જ માર્ક્સ મુજબ શોધશે

        let dbData = getDatabaseData(targetChap, targetTab);
        dbData.sort(() => 0.5 - Math.random()); // ડેટાબેઝને આડોઅવળો કરવો

        let addedForThisQ = 0;
        let neededForThisQ = neededMult - 1;

        for(let dbItem of dbData) {
            if(addedForThisQ >= neededForThisQ) break;

            let dbQText = dbItem.question || dbItem.q || "";
            // ડુપ્લીકેટ ચેક
            let isDuplicate = false;
            for(let sKey in selectedQuestions) {
                if(selectedQuestions[sKey].qText === dbQText) { isDuplicate = true; break; }
            }

            // ચેપ્ટર અને માર્ક્સ બંને મેચ થવા જોઈએ
            if(!isDuplicate && dbItem.marks == targetMarks) {
                let newKey = "rev_" + Math.random().toString(36).substr(2, 9);
                selectedQuestions[newKey] = {
                    qText: dbQText,
                    aText: dbItem.answer || dbItem.ans || "",
                    marks: targetMarks,
                    chap: targetChap,
                    tab: targetTab
                };
                addedForThisQ++;
                addedTotal++;
            }
        }
    }

    updateSummary();
    if(addedTotal > 0) {
        let decodeTxt = document.createElement("textarea");
        decodeTxt.innerHTML = `સ્માર્ટ રિવિઝન: ${addedTotal} એક્સ્ટ્રા પ્રશ્નો (સેમ ચેપ્ટર અને ગુણ મુજબ) ઉમેરાઈ ગયા છે!`;
        alert(decodeTxt.value);
    }
}
