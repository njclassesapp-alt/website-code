function autoReplaceQuestion() {
    if(!currentReplaceKey || tempReplaceOptions.length === 0) {
        alert("બીજો કોઈ નવો પ્રશ્ન ઉપલબ્ધ નથી.");
        return;
    }
    // લિસ્ટમાંથી રેન્ડમ પ્રશ્ન લેવો
    let randomItem = tempReplaceOptions[Math.floor(Math.random() * tempReplaceOptions.length)];
    
    selectedQuestions[currentReplaceKey].qText = randomItem.qText;
    selectedQuestions[currentReplaceKey].aText = randomItem.aText;
    
    closeModal('modal-replace');
    showPdfPreview();
}

