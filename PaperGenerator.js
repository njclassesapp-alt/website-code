function toggleChapter(chapId) {
    let chip = document.getElementById("chip-" + chapId);
    let index = selectedChapters.indexOf(chapId);
    if(index === -1) { selectedChapters.push(chapId); chip.classList.add("active"); openAccordions[chapId] = true; } 
    else { selectedChapters.splice(index, 1); chip.classList.remove("active"); delete openAccordions[chapId]; }
}

