let currentZoom = window.innerWidth <= 768 ? 0.42 : 1; 

function adjustZoom(step) {
    currentZoom += step;
    
    // ઝૂમની લિમિટ સેટ કરો (0.3 થી 2.0 સુધી)
    if (currentZoom < 0.3) currentZoom = 0.3;
    if (currentZoom > 2.0) currentZoom = 2.0;
    
    let previewBox = document.getElementById('pdf-preview-box');
    let scrollContainer = previewBox.parentElement; // પેપરની પાછળનો ડબ્બો
    
    // 🌟 ડાબી-જમણી બાજુ સ્કોલિંગ એક્ટિવ કરવા માટેનો જાદુ 🌟
    scrollContainer.style.overflowX = 'auto';
    scrollContainer.style.overflowY = 'auto';
    
    if (window.innerWidth <= 768) {
        // જો ઝૂમ 0.42 કે તેથી ઓછું હોય (એટલે કે ઓટો મોડ), તો સેન્ટરમાં રાખો
        if (currentZoom <= 0.42) {
            previewBox.style.left = "50%";
            previewBox.style.transform = `translateX(-50%) scale(${currentZoom})`;
            previewBox.style.transformOrigin = "top center";
            let newMargin = (1 / currentZoom) * 160;
            previewBox.style.marginBottom = `-${newMargin}%`;
            document.getElementById('zoom-display').innerText = "Auto";
        } 
        // 🌟 જો ઝૂમ મોટું હોય, તો સેન્ટર કાઢી નાખો જેથી બંને બાજુ સ્કોલ કરી શકાય 🌟
        else {
            previewBox.style.left = "0";
            previewBox.style.transform = `scale(${currentZoom})`;
            previewBox.style.transformOrigin = "top left";
            let newMargin = (1 / currentZoom) * 160;
            previewBox.style.marginBottom = `-${newMargin}%`;
            document.getElementById('zoom-display').innerText = Math.round(currentZoom * 100) + '%';
        }
    } else {
        // કમ્પ્યુટર માટે
        previewBox.style.transform = `scale(${currentZoom})`;
        if (currentZoom < 1) {
            previewBox.style.transformOrigin = "top center";
        } else {
            previewBox.style.transformOrigin = "top left";
        }
        document.getElementById('zoom-display').innerText = Math.round(currentZoom * 100) + '%';
    }
}

